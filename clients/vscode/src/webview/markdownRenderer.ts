hljs.registerLanguage('md', markdown);
hljs.registerLanguage('diff', diff);

marked.use({
	renderer: {
		code({ text, lang }: { text: string; lang?: string }) {
			const language = lang && hljs.getLanguage(lang) ? lang : 'plaintext';
			let highlighted: string;
			try {
				highlighted = hljs.highlight(text, { language }).value;
			} catch {
				highlighted = escHtml(text);
			}
			const langLabel = lang ? `<span class="code-lang">${escHtml(lang)}</span>` : '';
			const encoded   = encodeURIComponent(text);
			return `<div class="code-block"><div class="code-header">${langLabel}<button class="copy-btn" type="button" data-code="${encoded}">Copy</button></div><pre><code class="hljs language-${language}">${highlighted}</code></pre></div>`;
		},
	},
});

export function renderMarkdown(text: string): string {
	return marked(text) as string;
}

function escHtml(s: string): string {
	return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}
